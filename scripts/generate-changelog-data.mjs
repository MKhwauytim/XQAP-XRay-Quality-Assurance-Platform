// Regenerates src/data/changelog/latestUpdates.generated.ts from docs/edit logs/*.md.
//
// The in-app "سجل التحديثات" tab shows the app's own recent history without a backend or an
// LLM at runtime, so it can only surface what a build-time script can extract mechanically: each
// edit-log entry's own heading (`## vX.Y — YYYY-MM-DD — Category (scope): Title`), bucketed by
// its CLAUDE.md category into one of four Arabic-labelled groups. The Title itself stays in
// English/technical, as written by whoever made the edit — there is no runtime translation path.
//
// Only the LATEST 10 qualifying entries are embedded, not the whole history: docs/edit logs/ is
// tens of thousands of lines, and a previous "سجل الإصدارات" tab that embedded the full changelog
// was removed for bloating the single-file bundle (v72.0, 2026-08-13). Ten short entries add a
// few hundred bytes; the full archive stays out of the shipped app.
//
// Run via `npm run generate:changelog`. Also wired as a pre-hook on dev/build/typecheck/test so
// the generated file can never silently drift stale relative to docs/edit logs/ (see package.json).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const LOG_DIR = path.join(ROOT, "docs", "edit logs");
const OUT_FILE = path.join(ROOT, "src", "data", "changelog", "latestUpdates.generated.ts");
const LATEST_COUNT = 10;

/** CLAUDE.md edit-log categories -> the four buckets this tab displays. Anything not listed
 * here (Docs, Chore, Merge, Test, Docs+Test, ...) is internal housekeeping and is excluded. */
const CATEGORY_TO_BUCKET = {
  fix: "fix",
  security: "fix",
  add: "feature",
  feature: "feature",
  change: "enhancement",
  remove: "enhancement",
  refactor: "redesign",
};

const HEADING_RE =
  /^## (v[\d.]+) — (\d{4}-\d{2}-\d{2}) — ([A-Za-z+]+)(?:\s*\(([^)]*)\))?:\s*(.+)$/;

function verKey(v) {
  return v
    .replace(/^v/, "")
    .split(".")
    .map((n) => parseInt(n, 10) || 0);
}
function cmpVerDesc(a, b) {
  const ka = verKey(a.version);
  const kb = verKey(b.version);
  for (let i = 0; i < Math.max(ka.length, kb.length); i++) {
    const d = (kb[i] || 0) - (ka[i] || 0);
    if (d !== 0) return d;
  }
  return 0;
}

const files = readdirSync(LOG_DIR).filter((f) => f.endsWith(".md"));

const entries = [];
for (const file of files) {
  const text = readFileSync(path.join(LOG_DIR, file), "utf8");
  for (const line of text.split("\n")) {
    const m = HEADING_RE.exec(line.trim());
    if (!m) continue;
    const [, version, date, categoryRaw, scope, title] = m;
    const bucket = CATEGORY_TO_BUCKET[categoryRaw.toLowerCase()];
    if (!bucket) continue;
    entries.push({ version, date, bucket, scope: scope ?? null, title: title.trim() });
  }
}

entries.sort((a, b) => {
  if (a.date !== b.date) return a.date < b.date ? 1 : -1;
  return cmpVerDesc(a, b);
});

const latest = entries.slice(0, LATEST_COUNT);

const banner =
  "// AUTO-GENERATED by scripts/generate-changelog-data.mjs from docs/edit logs/ — do not hand-edit.\n" +
  "// Regenerate with `npm run generate:changelog` (also runs automatically before dev/build/test/typecheck).\n";

const body =
  `import type { ChangelogEntry } from "./changelogTypes";\n\n` +
  `export const LATEST_UPDATES: ChangelogEntry[] = ${JSON.stringify(latest, null, 2)};\n`;

writeFileSync(OUT_FILE, banner + "\n" + body, "utf8");
console.log(`Wrote ${latest.length} changelog entries to ${path.relative(ROOT, OUT_FILE)}`);
